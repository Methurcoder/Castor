// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "Arils",
    platforms: [
        .macOS(.v14)
    ],
    products: [
        // Single umbrella product so the host app (Pomegranate) only ever links one library.
        .library(name: "Arils", targets: ["Arils"]),
        .executable(name: "arils-demo", targets: ["ArilsDemo"]),
        .executable(name: "arils-corpus", targets: ["ArilsCorpus"]),
        // The platform-independent part (no Apple frameworks): what a
        // Windows/Linux host needs to play an avatar rigged on a Mac.
        .library(name: "ArilsPortable", targets: ["ArilsCore", "ArilsMotion", "ArilsPlayer"]),
        .executable(name: "arils-motion-eval", targets: ["ArilsMotionEval"]),
    ],
    targets: [
        // Pure math, geometry, and the parameter model. No Apple framework dependencies
        // beyond Foundation/simd so it stays portable and trivially testable.
        .target(name: "ArilsCore"),

        // Rig document model, deformation evaluation, and the automatic rigging pipeline
        // (subject mask, face layout estimation, layer extraction, binding synthesis).
        .target(name: "ArilsRig", dependencies: ["ArilsCore", "ArilsPlayer", "ArilsFaceInference", "ArilsSubjectInference"]),

        // The platform-independent half of a rig: the document model, the
        // archive format and the deformation evaluators. Hosts that only play
        // avatars rigged elsewhere (the Windows/Linux preview) need just this
        // and ArilsMotion. ArilsRig re-exports it.
        .target(name: "ArilsPlayer", dependencies: ["ArilsCore"]),

        // In-process anime face detector and landmark model (Core ML) plus the
        // NMS / RoIAlign / heatmap steps between the networks. The models are
        // generated by Tools/AnimeFaceModels/export_coreml.py and the folder
        // holds only its README in Git; Arils runs without them. Optimized
        // even in Debug: unoptimized, the per-pixel loops take ~23 s per image
        // instead of ~0.6 s, which would stall face review in a Debug run.
        .target(
            name: "ArilsFaceInference",
            resources: [.copy("Resources/AnimeFaceModels")],
            swiftSettings: [.unsafeFlags(["-O"], .when(configuration: .debug))]
        ),

        // In-process anime character segmentation (ISNet, Core ML). The model
        // is generated by Tools/AnimeSegmentationModel/export_coreml.py and
        // the folder holds only its README in Git; Arils runs without it.
        // Optimized even in Debug for the per-pixel letterbox/resize loops.
        .target(
            name: "ArilsSubjectInference",
            resources: [.copy("Resources/AnimeSegmentationModel")],
            swiftSettings: [.unsafeFlags(["-O"], .when(configuration: .debug))]
        ),

        // Motion generation: idle motion, blink, gaze, lip sync, petting reaction,
        // and the sway physics simulator. Depends only on ArilsCore so the motion
        // system can be reused against any rig implementation.
        .target(name: "ArilsMotion", dependencies: ["ArilsCore"]),

        // Metal renderer and AppKit view. Consumes evaluated vertices from ArilsRig.
        // Shaders are compiled at runtime from source (ShaderSource.swift), so
        // building never requires the separately-downloaded Metal Toolchain.
        .target(name: "ArilsRender", dependencies: ["ArilsCore", "ArilsRig"]),

        // Umbrella facade: CharacterEngine ties rigging, motion, and rendering together
        // and exposes the one-call API the host app uses.
        .target(name: "Arils", dependencies: ["ArilsCore", "ArilsRig", "ArilsMotion", "ArilsRender"]),

        // Standalone demo app: `swift run arils-demo`.
        .executableTarget(name: "ArilsDemo", dependencies: ["Arils"]),
        // External-image evaluation harness. Corpus images stay outside Git;
        // only manifests and baseline CSVs belong in the repository.
        .executableTarget(
            name: "ArilsCorpus",
            dependencies: ["ArilsRig"],
            path: "Tools/ArilsCorpus"
        ),
        // Motion-quality harness: blink/saccade/phase/lip-sync metrics over
        // deterministic scenarios. Audio clips stay outside Git.
        .executableTarget(
            name: "ArilsMotionEval",
            dependencies: ["ArilsCore", "ArilsMotion"],
            path: "Tools/ArilsMotionEval",
            exclude: ["BASELINE.md"]
        ),

        .testTarget(name: "ArilsCoreTests", dependencies: ["ArilsCore"]),
        .testTarget(name: "ArilsRigTests", dependencies: ["ArilsRig", "ArilsPlayer"]),
        .testTarget(name: "ArilsFaceInferenceTests", dependencies: ["ArilsFaceInference"]),
        .testTarget(name: "ArilsSubjectInferenceTests", dependencies: ["ArilsSubjectInference"]),
        .testTarget(name: "ArilsMotionTests", dependencies: ["ArilsMotion"]),
        .testTarget(name: "ArilsTests", dependencies: ["Arils"]),
    ]
)
